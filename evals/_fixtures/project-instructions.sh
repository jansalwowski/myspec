#!/usr/bin/env bash
# Generate each eval case's project instructions: the CLAUDE.md and
# always-loaded .claude/rules/ its scaffold writes, as the case's
# execution.append_system_prompt in case.yaml.
#
# Why: `claude plugin eval` starts every run with CLAUDE_CODE_DISABLE_CLAUDE_MDS=1
# and `--setting-sources user`, so a scaffolded CLAUDE.md and .claude/rules/
# never load, and no case field or setting turns that back on. A real myspec
# project loads them in every session. See evals/README.md, "Project instructions".
#
# Usage: evals/_fixtures/project-instructions.sh [--check] [case...]
#   (no flag)  rewrite the generated block in each case.yaml (default: every case)
#   --check    write nothing; exit 1 and name each case whose block is missing,
#              stale, or present on a `description-only` case
#
# For each case it runs fixture.sh in a scratch workspace, the way the harness
# does (minimal environment, HOME beside the workspace), then renders CLAUDE.md
# and every always-loaded .claude/rules/**/*.md, sorted, the way Claude Code
# shows them to the model: frontmatter and block-level HTML comments removed,
# under its "Contents of … (project instructions…)" headers. The details, and
# the one deliberate difference, are in project-instructions.pl. A path-scoped
# rule loads in a real session only once the agent reads a matching file; the
# system prompt cannot mirror that, so it is left out. A case tagged
# `description-only` in prompt.md gets no block: its run sees skill
# descriptions and bodies only.
#
# Exit status: 0 up to date (or rewritten), 1 stale (--check), 2 a fixture
# failed, a case.yaml has its own `execution:` block, or a prompt.md sets
# append_system_prompt (the harness would let it replace the block).

set -uo pipefail

EVALS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HELPER="$EVALS_DIR/_fixtures/project-instructions.pl"
BEGIN_MARK="# BEGIN project-instructions: generated by evals/_fixtures/project-instructions.sh, do not edit"
END_MARK="# END project-instructions"

CHECK=0
cases=()
for a in "$@"; do
  case "$a" in
    --check) CHECK=1 ;;
    -h|--help) sed -n '2,29p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    -*) echo "project-instructions: unknown option $a" >&2; exit 2 ;;
    *) cases+=("$a") ;;
  esac
done
if [ "${#cases[@]}" -eq 0 ]; then
  for d in "$EVALS_DIR"/*/; do
    [ -f "$d/case.yaml" ] && cases+=("$(basename "$d")")
  done
fi

TMP=$(mktemp -d "${TMPDIR:-/tmp}/project-instructions.XXXXXX") || exit 2
trap 'rm -rf "$TMP"' EXIT

# yaml_block <text-file> — the generated case.yaml block. `|-` keeps the text
# exactly, with no trailing newline, as Claude Code trims it.
yaml_block() {
  printf '%s\n' "$BEGIN_MARK" "execution:" "  append_system_prompt: |-"
  awk '{ if ($0 == "") print ""; else print "    " $0 }' "$1"
  printf '%s\n' "$END_MARK"
}

# The case.yaml without its generated block (and the blank line before it).
strip_block() {
  awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
    $0 == b { skip = 1; if (held) held = 0; next }
    skip { if ($0 == e) skip = 0; next }
    { if (held) print ""; held = 0; if ($0 == "") { held = 1; next } print }
    END { if (held) print "" }' "$1"
}

# prompt_list <case> <tags|keys> — prompt.md frontmatter's tags (any YAML
# list form) or top-level keys, one per line. Fails when the helper cannot
# parse them, so a malformed list is an error rather than a missing tag.
prompt_list() {
  [ -f "$EVALS_DIR/$1/prompt.md" ] || return 0
  perl "$HELPER" "$2" "$EVALS_DIR/$1/prompt.md"
}

stale=() rc=0
for c in "${cases[@]}"; do
  dir="$EVALS_DIR/$c" yaml="$EVALS_DIR/$c/case.yaml"
  [ -f "$yaml" ] || { echo "project-instructions: $c has no case.yaml" >&2; rc=2; continue; }
  if strip_block "$yaml" | grep -qE '^execution:'; then
    echo "project-instructions: $c/case.yaml has its own execution: block; move those keys to prompt.md frontmatter" >&2
    rc=2; continue
  fi
  if ! keys=$(prompt_list "$c" keys) || ! tags=$(prompt_list "$c" tags); then
    echo "project-instructions: cannot read $c/prompt.md frontmatter" >&2
    rc=2; continue
  fi
  if printf '%s\n' "$keys" | grep -qxF append_system_prompt; then
    echo "project-instructions: $c/prompt.md sets append_system_prompt, which replaces the generated project instructions; remove it, or tag the case description-only and put the text in case.yaml" >&2
    rc=2; continue
  fi
  text="$TMP/$c.txt"
  : > "$text"
  if ! printf '%s\n' "$tags" | grep -qxF description-only && [ -f "$dir/fixture.sh" ]; then
    root="$TMP/$c.run"
    mkdir -p "$root/home/cwd"
    if ! err=$(cd "$root/home/cwd" && env -i PATH="$PATH" HOME="$root/home" TMPDIR="$TMP" TERM=dumb \
        bash "$dir/fixture.sh" 2>&1 >/dev/null); then
      echo "project-instructions: $c/fixture.sh failed: $err" >&2
      rc=2; continue
    fi
    if ! perl "$HELPER" render "$root/home/cwd" > "$text"; then rc=2; continue; fi
  fi
  want="$TMP/$c.yaml"
  strip_block "$yaml" > "$want"
  if [ -s "$text" ]; then
    printf '\n' >> "$want"
    yaml_block "$text" >> "$want"
  fi
  if ! cmp -s "$want" "$yaml"; then
    if [ "$CHECK" = 1 ]; then stale+=("$c"); else cp "$want" "$yaml" && echo "updated $c/case.yaml"; fi
  fi
done

if [ "${#stale[@]}" -gt 0 ]; then
  echo "project-instructions: stale in ${stale[*]}; run evals/_fixtures/project-instructions.sh" >&2
  [ "$rc" -gt 1 ] || rc=1
fi
exit "$rc"
